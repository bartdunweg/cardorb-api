-- One spelling for each English rarity, and TCGplayer's grade for old holo cards (Bart, 2026-09-14).
--
-- The API now reads TCGdex's rarity through rarity-names.ts and card-fact-corrections.ts. What is
-- stored was written with TCGdex's own words and is read back as it is, so it moves here to the same
-- words: a copy's rarity (cards.rarity), a binder's rule and a Pokédex setting (collections).
-- Counted before: 528 "Illustration rare" beside 82 "Illustration Rare", 95 and 8 Special
-- Illustration Rare, 24 and 14 Double Rare, 3 "Hyper rare", 1 "Rare Holo"; one Pokédex setting holds
-- "Illustration rare", "Special illustration rare" and "Hyper rare".

create temporary table rarity_spelling (old text primary key, new text not null);
insert into rarity_spelling (old, new) values
  ('double rare', 'Double Rare'),
  ('illustration rare', 'Illustration Rare'),
  ('special illustration rare', 'Special Illustration Rare'),
  ('hyper rare', 'Hyper Rare'),
  ('shiny rare', 'Shiny Rare'),
  ('shiny rare v', 'Shiny Rare V'),
  ('shiny rare vmax', 'Shiny Rare VMAX'),
  ('rare holo', 'Holo Rare'),
  ('rare holo lv.x', 'Holo Rare LV.X');

update cards c
set rarity = s.new
from rarity_spelling s
where lower(trim(c.rarity)) = s.old and c.rarity is distinct from s.new;

-- A binder's rule and a Pokédex setting keep a list of rarities; a Pokédex entry may carry a split
-- suffix ("Ultra Rare / v"), which is kept.
create or replace function pg_temp.respelled(list jsonb) returns jsonb language sql immutable as $$
  select coalesce(jsonb_agg(
    to_jsonb(coalesce(
      (select s.new || substr(e.value, length(split_part(e.value, ' / ', 1)) + 1)
       from rarity_spelling s where s.old = lower(trim(split_part(e.value, ' / ', 1)))),
      e.value
    )) order by e.ordinality), '[]'::jsonb)
  from jsonb_array_elements_text(list) with ordinality as e(value, ordinality)
$$;

update collections
set rule = jsonb_set(rule, '{rarities}', pg_temp.respelled(rule->'rarities'))
where jsonb_typeof(rule->'rarities') = 'array';

update collections
set pokedex = jsonb_set(pokedex, '{rarities}', pg_temp.respelled(pokedex->'rarities'))
where jsonb_typeof(pokedex->'rarities') = 'array';

