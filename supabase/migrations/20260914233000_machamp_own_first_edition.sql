update public.card_price_months m
set cents = (
  select array_agg(
    case when d.day is not null and m.cents[i] = d.old_cents then d.new_cents else m.cents[i] end
    order by i
  )
  from generate_series(1, array_length(m.cents, 1)) as i
  left join machamp_days d on d.month = m.month and d.day = i
)
where m.tcg_id = 'base1-8'
  and m.printing = '1st-edition-holofoil'
  and exists (select 1 from machamp_days d where d.month = m.month);
