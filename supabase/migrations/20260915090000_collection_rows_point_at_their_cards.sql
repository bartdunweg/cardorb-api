-- ── 2. The official set name ────────────────────────────────────────────────────────────────────
--
-- 86 of the owner's rows were filed under a name the catalogue does not title the set by (the audit of
-- 2026-09-14 counted 83). The API has shown the official name since
-- #306 and folds the two together, but the row kept the filing name, so a set filter and a card key
-- still carried it. Each pair below resolves to exactly one set, and every row moved has its card
-- (after step 1) in that set:
--   SV Black Star Promos      31 rows  svp        SVP Black Star Promos
--   Scarlet & Violet Base     30 rows  sv01       Scarlet & Violet
--   Wizard Black Star Promos  22 rows  basep      Wizards Black Star Promos
--   Pokemon Go                 2 rows  swsh10.5   Pokémon GO
--   Breakpoint                 1 row   xy9        BREAKpoint
-- No binder rule or Pokédex setting names any of the five (checked 2026-09-14).
with owner as (select id from public.profiles where username = 'bartdunweg')
update public.cards c
   set set_name = v.official
  from (values
    ('SV Black Star Promos', 'SVP Black Star Promos', 'svp'),
    ('Scarlet & Violet Base', 'Scarlet & Violet', 'sv01'),
    ('Wizard Black Star Promos', 'Wizards Black Star Promos', 'basep'),
    ('Pokemon Go', 'Pokémon GO', 'swsh10.5'),
    ('Breakpoint', 'BREAKpoint', 'xy9')
  ) as v(filed, official, set_id),
       owner
 where c.user_id = owner.id
   and coalesce(c.language, 'en') = 'en'
   and c.set_name = v.filed
   and exists (
     select 1 from public.catalogue_cards k
      where k.language = 'en' and k.id = c.tcg_id and k.set_id = v.set_id
   )
   and exists (
     select 1 from public.catalogue_sets s
      where s.language = 'en' and s.id = v.set_id and s.name = v.official
   );

-- ── 3. Copies recorded in a printing their card does not have ───────────────────────────────────
--
-- 14 of the owner's copies were recorded as normal on a promo that was only ever printed holo: eight
-- Sun & Moon tag team GX promos and six Sword & Shield V and VSTAR promos. TCGdex lists the holo
-- alone for each, and TCGplayer sells each as one product with a Holofoil printing and nothing else,
-- so holo is not a guess. The guard repeats the TCGdex half: every variant of the card is a holo.
--
-- Left as they are (2026-09-14), because the right answer is not certain:
--   * Three Rares recorded as normal (White Flare Emboar 013 and Gothitelle 043, Black Bolt Haxorus
--     070): both sources list a holo and a reverse holo, so which one the copy is needs the owner.
--   * Team Rocket's Meowth, Wizards Black Star Promos 18, recorded holo: TCGdex lists a holo only,
--     TCGplayer sells it as Normal only. The sources disagree, and which one card-printings.ts
--     follows is being changed on another branch.
with owner as (select id from public.profiles where username = 'bartdunweg')
update public.cards c
   set finish = 'holo'
  from owner
 where c.user_id = owner.id
   and coalesce(c.language, 'en') = 'en'
   and c.finish = 'normal'
   and c.tcg_id in (
     'smp-SM167', 'smp-SM168', 'smp-SM169', 'smp-SM191', 'smp-SM192', 'smp-SM193', 'smp-SM201',
     'smp-SM210', 'swshp-SWSH179', 'swshp-SWSH181', 'swshp-SWSH183', 'swshp-SWSH260',
     'swshp-SWSH262', 'swshp-SWSH291'
   )
   and exists (
     select 1 from public.catalogue_cards k
      where k.language = 'en'
        and k.id = c.tcg_id
        and jsonb_array_length(k.variants) > 0
        and not exists (
          select 1 from jsonb_array_elements(k.variants) e where e->>'type' is distinct from 'holo'
        )
   );
