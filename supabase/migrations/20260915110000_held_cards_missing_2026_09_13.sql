--
-- Kanto's line on Home read EUR 19,750 on the 12th, 16,200 on the 13th and 19,794 on the 14th. On
-- the 13th the collection snapshot still priced held cards itself, and for these promos and gallery
-- cards (SVP, XY promos, the Trainer and Galarian Galleries, Base2-64, XY6-77a) it wrote only the old
-- `market` series; the every-card pass left held cards to the snapshot, so no printing of theirs
-- had a figure that day. Migration 20260915010000 (#444) then deleted that `market` series, and the
-- day had no reading at all: 36 of Kanto's copies counted as unpriced for one day.
--
-- The figures are tcgcsv's archive for 2026-09-13 (prices-2026-09-13.ppmd.7z, category 3), each
-- card's own product and printing as backfill-card-prices.mjs `--only daily` reads them, at that
-- day's rate, the ECB's of Friday 2026-09-11 (0.86266 euros a dollar), in cents: what
-- `node scripts/backfill-card-prices.mjs --only daily --ids <these> --from 2026-09-13 --to 2026-09-13`
-- would write. Every one lies within 0.8 percent of the same printing's 12th and 14th.
--
-- Fills the hole and nothing else: a day already stored stays (merge_price_days with the stored
-- month first), so running it again, or after a backfill wrote the day, changes nothing.
